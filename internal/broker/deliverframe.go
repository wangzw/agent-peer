// deliverRequest is the broker-level form of a kind-400 delivery frame. It is
// the subset a delivery needs; transport details stay on link.Frame.
type deliverRequest struct {
	MessageID, SenderName, SenderRef, TargetName, TargetRef string
	Remaining                                               time.Duration
	Text                                                    string
}

const (
	uuidLen   = 36
	minRefLen = 6
	maxRefLen = 12
	// maxNameBytes bounds the raw sender and target names a peer may put in a
	// delivery request. The receiver copies these names into error replies,
	// log lines and the dedupe table, so an unbounded name would let a paired
	// peer make it hold an arbitrarily large string.
	maxNameBytes = 1024
)

// newMessageID returns a random UUID version 4 in lowercase 8-4-4-4-12 form.
// The identifier is generated by the sender and reused when a delivery is
// retried, so the receiver's dedupe table can recognize the retry.
func newMessageID() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		// crypto/rand never fails on supported platforms; a silent fallback
		// would emit a predictable identifier and defeat dedupe.
		panic("broker: crypto/rand failed: " + err.Error())
	}
	b[6] = b[6]&0x0f | 0x40 // version 4
	b[8] = b[8]&0x3f | 0x80 // RFC 4122 variant
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

// isUUID reports whether s has the 36-character 8-4-4-4-12 hexadecimal shape.
// The version and variant bits are not checked, and either case is accepted:
// the receiver only needs the identifier to be a UUID, not one this version
// would generate.
func isUUID(s string) bool {
	if len(s) != uuidLen {
		return false
	}
	for i := 0; i < len(s); i++ {
		switch i {
		case 8, 13, 18, 23:
			if s[i] != '-' {
				return false
			}
		default:
			if !isHexDigit(s[i]) {
				return false
			}
		}
	}
	return true
}

// isRefSyntax reports the disambiguation ref grammar: 6 to 12 lowercase
// hexadecimal characters. Values from a peer reach FormatAddress, which panics
// on a malformed ref, so they must pass this check first.
func isRefSyntax(s string) bool {
	if len(s) < minRefLen || len(s) > maxRefLen {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if (c < '0' || c > '9') && (c < 'a' || c > 'f') {
			return false
		}
	}
	return true
}

func isHexDigit(c byte) bool {
	return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F')
}

// encodeDeliverRequest builds a kind-400 frame. The body is an A2A Message
// whose message_id equals the delivery identifier, with role ROLE_USER and one
// text part, so the receiver's session shows the same identifier and direction
// the sender chose.
func encodeDeliverRequest(r deliverRequest) (link.Frame, error) {
	msg := &deliverpb.DeliverRequest{
		MessageId:       r.MessageID,
		SenderName:      r.SenderName,
		SenderRef:       r.SenderRef,
		TargetName:      r.TargetName,
		TargetRef:       r.TargetRef,
		RemainingBudget: durationpb.New(r.Remaining),
		Body: &deliverpb.Message{
			MessageId: r.MessageID,
			Role:      deliverpb.Role_ROLE_USER,
			Parts:     []*deliverpb.Part{{Content: &deliverpb.Part_Text{Text: r.Text}}},
		},
	}
	payload, err := proto.Marshal(msg)
	if err != nil {
		return link.Frame{}, fmt.Errorf("broker: encode delivery request: %w", err)
	}
	return link.Frame{Kind: link.FrameKind(deliverpb.KindDeliver), Payload: payload}, nil
}

// decodeDeliverRequest validates and unpacks a kind-400 frame. Every failure is
// invalid_argument with the "Not sent" prefix, so the sender reports that
// nothing was written. The role is deliberately not checked: this version
// always sends ROLE_USER, but a future role must not make a request unreadable.
func decodeDeliverRequest(f link.Frame) (deliverRequest, *Error) {
	if f.Kind != link.FrameKind(deliverpb.KindDeliver) {
		return deliverRequest{}, badDeliverRequest("unexpected frame kind %d, want %d", f.Kind, deliverpb.KindDeliver)
	}
	msg := new(deliverpb.DeliverRequest)
	if err := proto.Unmarshal(f.Payload, msg); err != nil {
		return deliverRequest{}, badDeliverRequest("malformed delivery request: %v", err)
	}
	id := msg.GetMessageId()
	if !isUUID(id) {
		return deliverRequest{}, badDeliverRequest("message id %q is not a UUID", id)
	}
	budget := msg.GetRemainingBudget()
	if budget == nil {
		return deliverRequest{}, badDeliverRequest("message %s has no remaining budget", id)
	}
	if msg.GetSenderName() == "" {
		return deliverRequest{}, badDeliverRequest("message %s has no sender name", id)
	}
	if n := len(msg.GetSenderName()); n > maxNameBytes {
		return deliverRequest{}, badDeliverRequest("message %s has a sender name of %d bytes, over the %d-byte limit", id, n, maxNameBytes)
	}
	if !isRefSyntax(msg.GetSenderRef()) {
		return deliverRequest{}, badDeliverRequest("message %s has an invalid sender ref %q", id, msg.GetSenderRef())
	}
	if msg.GetTargetName() == "" {
		return deliverRequest{}, badDeliverRequest("message %s has no target name", id)
	}
	if n := len(msg.GetTargetName()); n > maxNameBytes {
		return deliverRequest{}, badDeliverRequest("message %s has a target name of %d bytes, over the %d-byte limit", id, n, maxNameBytes)
	}
	if ref := msg.GetTargetRef(); ref != "" && !isRefSyntax(ref) {
		return deliverRequest{}, badDeliverRequest("message %s has an invalid target ref %q", id, ref)
	}
	body := msg.GetBody()
	if body == nil {
		return deliverRequest{}, badDeliverRequest("message %s has no body", id)
	}
	if body.GetMessageId() != id {
		return deliverRequest{}, badDeliverRequest("body message id %q does not match %q", body.GetMessageId(), id)
	}
	parts := body.GetParts()
	if len(parts) != 1 {
		return deliverRequest{}, badDeliverRequest("message %s has %d parts, want 1", id, len(parts))
	}
	if parts[0].GetText() == "" {
		return deliverRequest{}, badDeliverRequest("message %s has empty text", id)
	}
	return deliverRequest{
		MessageID:  id,
		SenderName: msg.GetSenderName(),
		SenderRef:  msg.GetSenderRef(),
		TargetName: msg.GetTargetName(),
		TargetRef:  msg.GetTargetRef(),
		Remaining:  budget.AsDuration(),
		Text:       parts[0].GetText(),
	}, nil
}

// badDeliverRequest reports a delivery request this Broker cannot process. The
// caller uses the message only for its own log; the sender gets the code.
func badDeliverRequest(format string, args ...any) *Error {
	return notSent(localpb.ErrorCode_ERROR_CODE_INVALID_ARGUMENT, format, args...)
}

// encodeDeliverResult builds a kind-401 frame. A nil e reports success. The
// error branch carries only the code and message: a peer's own fingerprint is
// the sender's to attach, so an originating_broker_fingerprint inside the
// request is never relayed.
func encodeDeliverResult(e *Error) link.Frame {
	msg := &deliverpb.DeliverResult{
		Result: &deliverpb.DeliverResult_Delivered{Delivered: &deliverpb.Delivered{}},
	}
	if e != nil {
		msg.Result = &deliverpb.DeliverResult_Error{Error: &localpb.ErrorDetail{
			Code:    e.Code,
			Message: e.Message,
		}}
	}
	payload, err := proto.Marshal(msg)
	if err != nil {
		// Marshaling these messages can only fail on an invalid UTF-8 string.
		// An empty payload makes the sender treat the reply as malformed,
		// which it maps to delivery_unknown, never to success.
		payload = nil
	}
	return link.Frame{Kind: link.FrameKind(deliverpb.KindDeliverResult), Payload: payload}
}

// decodeDeliverResult unpacks a kind-401 frame. A successful delivery yields
// (nil, nil); an error result yields the detail. Any other frame or a result
// that carries neither branch is an error, because a reply the sender cannot
// understand must not count as delivered.
func decodeDeliverResult(f link.Frame) (*localpb.ErrorDetail, error) {
	if f.Kind != link.FrameKind(deliverpb.KindDeliverResult) {
		return nil, fmt.Errorf("broker: unexpected delivery result frame kind %d, want %d", f.Kind, deliverpb.KindDeliverResult)
	}
	msg := new(deliverpb.DeliverResult)
	if err := proto.Unmarshal(f.Payload, msg); err != nil {
		return nil, fmt.Errorf("broker: decode delivery result: %w", err)
	}
	switch result := msg.GetResult().(type) {
	case *deliverpb.DeliverResult_Delivered:
		return nil, nil
	case *deliverpb.DeliverResult_Error:
		if result.Error == nil {
			return nil, fmt.Errorf("broker: delivery result has no error detail")
		}
		return result.Error, nil
	default:
		return nil, fmt.Errorf("broker: delivery result carries no result")
	}
}
